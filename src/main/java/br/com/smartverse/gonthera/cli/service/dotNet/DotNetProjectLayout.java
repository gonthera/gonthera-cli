package br.com.smartverse.gonthera.cli.service.dotNet;

import br.com.smartverse.gonthera.cli.model.Properties;
import br.com.smartverse.gonthera.cli.model.Entities;
import br.com.smartverse.gonthera.cli.service.common.Common;
import br.com.smartverse.gonthera.cli.service.common.FieldsMapper;
import java.io.IOException;
import java.nio.file.*;
import java.util.*;
import java.util.stream.Collectors;

/** Places generated C# files in their owning assemblies and preserves consumer files. */
public final class DotNetProjectLayout {
    private final Path root;
    private final String name;
    private final Properties model;
    private static final String HEADER = "// <auto-generated />\n";
    private final Map<String, Set<String>> namespaces = new LinkedHashMap<>();

    private DotNetProjectLayout(Path root, Properties model) {
        this.root = root;
        this.name = model.getMainPackage();
        this.model = model;
        for (String layer : List.of("Domain", "Application", "Infrastructure", "Api")) namespaces.put(layer, new TreeSet<>());
    }

    public static void assemble(Path root, Path staging, Properties model) {
        try { new DotNetProjectLayout(root, model).write(staging); }
        catch (IOException ex) { throw new IllegalStateException("Could not generate .NET solution", ex); }
    }

    private void write(Path staging) throws IOException {
        for (String layer : namespaces.keySet()) {
            Path generated = project(layer).resolve("Generated");
            if (Files.exists(generated)) {
                try (var paths = Files.walk(generated)) {
                    for (Path path : paths.sorted(Comparator.reverseOrder()).collect(Collectors.toList())) Files.delete(path);
                }
            }
        }
        List<Path> files;
        try (var stream = Files.walk(staging)) {
            files = stream.filter(p -> p.toString().endsWith(".cs")).collect(Collectors.toList());
        }
        for (Path file : files) {
            Path relative = staging.relativize(file);
            String folder = relative.getName(0).toString();
            String filename = file.getFileName().toString();
            String layer = layer(folder, filename);
            if (folder.equals("Controllers") || filename.equals("AddScoped.cs")) continue;
            String category = folder.equals("Repositories") && isRepositoryContract(filename) ? "Repositories" : folder;
            String ns = name + "." + layer + "." + category;
            if (relative.getNameCount() > 2) ns += "." + relative.getParent().subpath(1,relative.getParent().getNameCount()).toString().replace('/', '.');
            namespaces.get(layer).add(ns);
            String content = Files.readString(file).replace(name + "." + name + "_Gen", name + ".Infrastructure");
            content = content.replace("public ApiDbContext _context;", "protected readonly ApiDbContext _context;");
            content = content.replace("using Microsoft.AspNetCore.Builder;", "using Microsoft.Extensions.DependencyInjection;")
                .replace("WebApplicationBuilder builder", "IServiceCollection services").replace("builder.Services.", "services.");
            content = content.replaceAll("namespace [^\\s{;]+", "namespace " + ns);
            if (folder.equals("Entities") || folder.equals("Dtos") || filename.endsWith("Input.cs") || filename.endsWith("Output.cs")) {
                content = content.replace("public class ", "public partial class ");
            }
            if (folder.equals("Repositories") && !isRepositoryContract(filename)) {
                String type = filename.substring(0, filename.length()-3);
                content = content.replace("using " + name + ".Config.Database;", "")
                    .replace("public class " + type, "public abstract class " + type + "Base")
                    .replace("public " + type + "(", "protected " + type + "Base(");
                filename = type + "Base.cs";
                custom("Infrastructure", "Repositories/"+type+".cs", ns, type, type+"Base",
                    "public "+type+"(ApiDbContext context) : base(context) { }", "");
            }
            if (file.getFileName().toString().equals("CustomDbContext.cs")) {
                content = Common.loadWxsd("layeredcontext").replace("<<namespace>>",ns)
                    .replace("<<dbSet>>",model.getEntities().stream().filter(e -> !e.isOnlyDTO()).map(e -> {
                        String type=Common.firstCharacterUpperCase(e.getEntityName());
                        return "public DbSet<"+type+"Entity> "+type+"Context { get; set; }";
                    }).collect(Collectors.joining("\n")));
                custom("Infrastructure", "Data/ApiDbContext.cs",ns,"ApiDbContext","CustomDbContext",
                    "public ApiDbContext(Microsoft.EntityFrameworkCore.DbContextOptions<ApiDbContext> options) : base(options) { }", "partial ");
            }
            generated(layer, relative.getParent().resolve(filename).toString(), content);
            if (folder.equals("Entities") || folder.equals("Dtos")) {
                String type=filename.substring(0,filename.length()-3);
                writeOnce(project(layer).resolve(folder).resolve(type+".Custom.cs"), "namespace "+ns+";\npublic partial class "+type+" { }\n");
            }
        }
        services();
        projects();
        injection();
        String solution = "<Solution>\n";
        for (String layer : namespaces.keySet()) solution += "  <Project Path=\""+name+"."+layer+"/"+name+"."+layer+".csproj\" />\n";
        writeOnce(root.resolve(name+".slnx"), solution+"</Solution>\n");
        writeOnce(root.resolve(".gitignore"), "**/bin/\n**/obj/\n");
    }

    private boolean isRepositoryContract(String filename) {
        return filename.equals("IBaseRepository.cs") || model.getEntities().stream().anyMatch(entity ->
                filename.equals("I" + Common.firstCharacterUpperCase(entity.getEntityName()) + "Repository.cs"));
    }

    private String layer(String folder, String filename) {
        if (folder.equals("Entities") || folder.equals("Enums")) return "Domain";
        if (folder.equals("Dtos") || folder.equals("Converters") || (folder.equals("Repositories") && isRepositoryContract(filename))
                || filename.equals("RequestData.cs") || filename.equals("ResponseData.cs")
                || (folder.equals("Endpoints") && !filename.endsWith("Primitive.cs"))) return "Application";
        if (folder.equals("Controllers") || folder.equals("Endpoints")) return "Api";
        return "Infrastructure";
    }

    private void services() throws IOException {
        for (Entities entity : model.getEntities()) {
            if(entity.isOnlyDTO()) continue;
            String type=Common.firstCharacterUpperCase(entity.getEntityName());
            String key=FieldsMapper.getFieldTypeEntity(entity.getEntityFields().stream().filter(f -> f.getMetadata().isKey()).findFirst().orElseThrow().getFieldProperties().getFieldType());
            String ns=name+".Application.Services";
            namespaces.get("Application").add(ns);
            generated("Application", "Services/"+type+"ServiceBase.cs", render("applicationservice",ns,type,key,entity.getEntityName()));
            custom("Application","Services/"+type+"Service.cs",ns,type+"Service",type+"ServiceBase",
                "public "+type+"Service(I"+type+"Repository repository) : base(repository) { }", "");
            if (entity.isGenerateDefaultControllers()) {
                ns=name+".Api.Controllers";
                namespaces.get("Api").add(ns);
                generated("Api","Controllers/"+type+"ControllerBase.cs",render("layeredcontroller",ns,type,key,entity.getEntityName()));
                custom("Api","Controllers/"+type+"Controller.cs",ns,type+"Controller",type+"ControllerBase",
                    "public "+type+"Controller("+type+"Service service) : base(service) { }", entity.isControllerAbstract()?"abstract ":"");
            }
        }
    }

    private String render(String template,String ns,String type,String key,String route) {
        return Common.loadWxsd(template).replace("<<namespace>>",ns).replace("<<entity>>",type).replace("<<key>>",key).replace("<<route>>",route);
    }

    private void projects() throws IOException {
        for (String layer : namespaces.keySet()) {
            String refs="";
            List<String> dependencies=layer.equals("Domain")?List.of():layer.equals("Application")?List.of("Domain"):
                layer.equals("Infrastructure")?List.of("Domain","Application"):List.of("Domain","Application","Infrastructure");
            for(String dep:dependencies) refs+="    <ProjectReference Include=\"../"+name+"."+dep+"/"+name+"."+dep+".csproj\" />\n";
            if(layer.equals("Infrastructure")) {
                refs+="    <PackageReference Include=\"Npgsql.EntityFrameworkCore.PostgreSQL\" Version=\"10.0.0\" />\n";
                if(namespaces.get(layer).stream().anyMatch(n -> n.contains(".Messaging"))) refs+="    <PackageReference Include=\"RabbitMQ.Client\" Version=\"6.8.1\" />\n"
                    + "    <PackageReference Include=\"Microsoft.Extensions.Hosting.Abstractions\" Version=\"10.0.0\" />\n"
                    + "    <PackageReference Include=\"Microsoft.Extensions.Configuration.Abstractions\" Version=\"10.0.0\" />\n";
            }
            String csproj=Common.loadWxsd("project").replace("<<references>>",refs);
            if(layer.equals("Api")) csproj=csproj.replace("Microsoft.NET.Sdk\"", "Microsoft.NET.Sdk.Web\"");
            writeOnce(project(layer).resolve(name+"."+layer+".csproj"),csproj);
            Set<String> imports=new TreeSet<>(namespaces.get(layer));
            for(String dep:dependencies) imports.addAll(namespaces.get(dep));
            String globals=(layer.equals("Infrastructure") ? "global using Microsoft.Extensions.DependencyInjection;\n" : "") + imports.stream().map(n -> "global using "+n+";").collect(Collectors.joining("\n"));
            generated(layer,"GlobalUsings.cs",globals);
        }
    }

    private void injection() throws IOException {
        String body="";
        for(Entities entity:model.getEntities()) {
            if(entity.isOnlyDTO()) continue;
            String type=Common.firstCharacterUpperCase(entity.getEntityName());
            body+="        services.AddScoped<I"+type+"Repository, "+type+"Repository>();\n";
            body+="        services.AddScoped<"+type+"Service>();\n";
        }
        generated("Infrastructure","DependencyInjection.cs","using Microsoft.Extensions.DependencyInjection;\nnamespace "+name+".Infrastructure;\n"
            +"public static class DependencyInjection { public static IServiceCollection AddGeneratedInfrastructure(this IServiceCollection services) {\n"+body+"return services; } }\n");
        writeOnce(project("Api").resolve("Program.cs"), "using Microsoft.AspNetCore.Builder;\nusing Microsoft.Extensions.DependencyInjection;\nusing Microsoft.EntityFrameworkCore;\nusing "+name+".Infrastructure;\n"
            +"var builder = WebApplication.CreateBuilder(args);\nbuilder.Services.AddControllers();\nbuilder.Services.AddGeneratedInfrastructure();\n"
            +"builder.Services.AddDbContext<ApiDbContext>(options => options.UseNpgsql(builder.Configuration[\"ConnectionStrings:Default\"]));\n"
            +"var app = builder.Build();\napp.MapControllers();\napp.Run();\n");
    }

    private Path project(String layer) { return root.resolve(name+"."+layer); }
    private void generated(String layer,String relative,String content) throws IOException {
        Path file=project(layer).resolve("Generated").resolve(relative);
        Files.createDirectories(file.getParent()); Files.writeString(file,HEADER+content);
    }
    private void custom(String layer,String relative,String ns,String type,String parent,String constructor,String kind) throws IOException {
        String text=Common.loadWxsd("customclass").replace("<<namespace>>",ns).replace("<<entity>>",type)
            .replace("<<base>>",parent).replace("<<constructor>>",constructor).replace("<<kind>>",kind);
        writeOnce(project(layer).resolve(relative),text);
    }
    private void writeOnce(Path path,String content) throws IOException {
        Files.createDirectories(path.getParent());
        if(!Files.exists(path)) Files.writeString(path,content,StandardOpenOption.CREATE_NEW);
    }
}
