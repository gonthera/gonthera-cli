package br.com.smartverse.gonthera.cli;

import br.com.smartverse.gonthera.cli.enuns.Language;
import br.com.smartverse.gonthera.cli.model.Entities;
import br.com.smartverse.gonthera.cli.model.EntityFields;
import br.com.smartverse.gonthera.cli.model.FieldMetadata;
import br.com.smartverse.gonthera.cli.model.FieldProperties;
import br.com.smartverse.gonthera.cli.model.Properties;
import br.com.smartverse.gonthera.cli.service.common.Common;
import br.com.smartverse.gonthera.cli.service.dotNet.GenerateDotNet;
import org.junit.Test;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;

import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

public class DotNetOutputLayoutTest {

    @Test
    public void generatesDotNetSourcesInDedicatedDirectoriesWithoutHandlers() throws Exception {
        Path root = Files.createTempDirectory("gonthera-dotnet-layout-");
        Files.createDirectories(root.resolve("static"));
        Properties project = project(false);

        generate(root, project);

        assertFile(root.resolve("ExampleBackend.Domain/Generated/Entities/CustomerEntity.cs"));
        assertFile(root.resolve("ExampleBackend.Domain/Entities/CustomerEntity.Custom.cs"));
        assertFile(root.resolve("ExampleBackend.Application/Generated/Dtos/CustomerDTO.cs"));
        assertFile(root.resolve("ExampleBackend.Application/Generated/Repositories/ICustomerRepository.cs"));
        assertFile(root.resolve("ExampleBackend.Infrastructure/Generated/Repositories/CustomerRepositoryBase.cs"));
        assertFile(root.resolve("ExampleBackend.Api/Controllers/CustomerController.cs"));
        assertFile(root.resolve("ExampleBackend.Infrastructure/Data/ApiDbContext.cs"));
        assertFile(root.resolve("ExampleBackend.slnx"));
        String controller = readFile(root.resolve("ExampleBackend.Api/Generated/Controllers/CustomerControllerBase.cs"));
        assertTrue(controller.contains("public abstract class CustomerControllerBase"));
        assertTrue(controller.contains("CustomerService"));
        assertFalse(controller.contains("Repository"));
        assertFalse(Files.exists(root.resolve("ExampleBackend_gen")));
        assertFalse(readFile(root.resolve("ExampleBackend.Domain/ExampleBackend.Domain.csproj")).contains("PackageReference"));
        assertTrue(readFile(root.resolve("ExampleBackend.Domain/Generated/Entities/CustomerEntity.cs")).contains("public partial class"));
        assertTrue(readFile(root.resolve("ExampleBackend.Application/Generated/Dtos/CustomerDTO.cs")).startsWith("// <auto-generated />"));
        Path program = root.resolve("ExampleBackend.Api/Program.cs");
        Files.writeString(program, Files.readString(program) + "\n// handwritten bootstrap\n");
        Path custom = root.resolve("ExampleBackend.Application/Services/CustomerService.cs");
        Files.writeString(custom, Files.readString(custom) + "\n// consumer customization\n");
        Path stale = root.resolve("ExampleBackend.Domain/Generated/Entities/Obsolete.cs");
        Files.writeString(stale, "// obsolete");
        generate(root, project);
        assertTrue(readFile(custom).contains("consumer customization"));
        assertTrue(readFile(program).contains("handwritten bootstrap"));
        assertFalse(Files.exists(stale));
        assertTrue(readFile(root.resolve("ExampleBackend.Infrastructure/Generated/DependencyInjection.cs"))
                .contains("AddScoped<ICustomerRepository, CustomerRepository>"));
    }

    @Test
    public void generatesAbstractDotNetControllerWhenConfigured() throws Exception {
        Path root = Files.createTempDirectory("gonthera-dotnet-abstract-controller-");
        Files.createDirectories(root.resolve("static"));

        generate(root, project(true));

        String controller = readFile(root.resolve("ExampleBackend.Api/Controllers/CustomerController.cs"));
        assertTrue(controller.contains("public abstract class CustomerController"));
        assertTrue(controller.contains("public CustomerController(CustomerService service)"));
    }

    @Test
    public void onlyDtoDoesNotGeneratePersistenceOrServices() throws Exception {
        Path root = Files.createTempDirectory("gonthera-dotnet-onlydto-");
        Properties project = project(false);
        project.getEntities().get(0).setOnlyDTO(true);
        generate(root, project);
        assertFile(root.resolve("ExampleBackend.Application/Generated/Dtos/CustomerDTO.cs"));
        assertFalse(Files.exists(root.resolve("ExampleBackend.Domain/Generated/Entities/CustomerEntity.cs")));
        assertFalse(Files.exists(root.resolve("ExampleBackend.Application/Services/CustomerService.cs")));
        assertFalse(Files.exists(root.resolve("ExampleBackend.Infrastructure/Repositories/CustomerRepository.cs")));
        assertFalse(Files.exists(root.resolve("ExampleBackend.Api/Controllers/CustomerController.cs")));
    }

    @Test
    public void entityStartingWithIDoesNotTurnConcreteRepositoryIntoContract() throws Exception {
        Path root = Files.createTempDirectory("gonthera-dotnet-invoice-");
        Properties project = project(false);
        project.getEntities().get(0).setEntityName("invoice");
        project.getEntities().get(0).setTableName("invoice");
        generate(root, project);
        assertFile(root.resolve("ExampleBackend.Infrastructure/Generated/Repositories/InvoiceRepositoryBase.cs"));
        assertFile(root.resolve("ExampleBackend.Application/Generated/Repositories/IInvoiceRepository.cs"));
        assertFalse(Files.exists(root.resolve("ExampleBackend.Application/Generated/Repositories/InvoiceRepository.cs")));
    }

    private void generate(Path root, Properties project) {
        String previousDirectory = System.getProperty("user.dir");
        try {
            System.setProperty("user.dir", root.toString());
            Common.properties = project;
            GenerateDotNet.generateSource(project);
        } finally {
            System.setProperty("user.dir", previousDirectory);
        }
    }

    private void assertFile(Path file) {
        assertTrue("Expected generated file " + file, Files.isRegularFile(file));
    }

    private String readFile(Path file) throws Exception {
        return new String(Files.readAllBytes(file), StandardCharsets.UTF_8);
    }

    private Properties project(boolean controllerAbstract) {
        FieldProperties fieldProperties = new FieldProperties();
        fieldProperties.setFieldType("uuid");
        FieldMetadata metadata = new FieldMetadata();
        metadata.setKey(true);

        EntityFields id = new EntityFields();
        id.setFieldName("id");
        id.setFieldProperties(fieldProperties);
        id.setMetadata(metadata);

        Entities customer = new Entities();
        customer.setEntityName("customer");
        customer.setTableName("customer");
        customer.setEntityFields(Collections.singletonList(id));
        customer.setGenerateDefaultControllers(true);
        customer.setControllerAbstract(controllerAbstract);

        Properties project = new Properties();
        project.setMainPackage("ExampleBackend");
        project.setProjectName("example-backend");
        project.setLanguage(Language.DOTNET);
        project.setEntities(Collections.singletonList(customer));
        project.setEndpoints(Collections.emptyList());
        project.setEnums(Collections.emptyList());
        return project;
    }
}
